    FROM BID_FAILURE_TYPE
    WHERE BID_FAIL_TYPE_NAME = '낙찰포기';

    -- 낙찰 실패 이력
    INSERT INTO BID_FAILURE_HISTORY(BID_FAIL_HISTORY_ID,BID_RESULT_ID,BID_FAIL_TYPE_ID)
    VALUES(BID_FAIL_HISTORY_SEQ.NEXTVAL,V_RESULT_ID,N_BID_FAIL_TYPE_ID);

    SELECT NVL(PENALTY_TYPE_ID,0) INTO N_PENALTY_TYPE_ID
    FROM PENALTY_ASSIGN_TYPE
    WHERE PENALTY_TYPE_NAME = '자동';

    N_PENALTY_ID := PENALTY_SEQ.NEXTVAL;
    
    -- 구매자 패널티 부여
    INSERT INTO PENALTY_HISTORY(PENALTY_ID,USER_ID,PENALTY_TYPE_ID,ADMIN_ACCOUNT_ID,PENALTY_SCORE)
    VALUES(N_PENALTY_ID,V_USER_ID,N_PENALTY_TYPE_ID,NULL,1);
    
    SELECT SUM(PH.PENALTY_SCORE) INTO V_TOTAL_PENALTY_SCORE
    FROM PENALTY_HISTORY PH LEFT OUTER JOIN PENALTY_CANCEL PC
         ON PH.PENALTY_ID = PC.PENALTY_ID
    WHERE PH.USER_ID = V_USER_ID
      AND PENALTY_CANCEL_ID IS NULL;
   
    -- 패널티 점수가 일정치 이상(1점 초과)이면 제재 발생
    IF V_TOTAL_PENALTY_SCORE > 1 THEN
        CASE
            -- 4점 이상: 영구 정지
            WHEN V_TOTAL_PENALTY_SCORE >= 4
            THEN V_PENALTY_END_DATE := TO_DATE('9999-12-31 23:59:59', 'YYYY-MM-DD HH24:MI:SS');

            -- 3점 이상: 30일 정지
            -- 오늘을 기준으로 30일 뒤 23시59분59초까지 계정 정지
            WHEN V_TOTAL_PENALTY_SCORE >= 3
            THEN V_PENALTY_END_DATE := TRUNC(SYSDATE + 30) + (1 - 1/86400);

            -- 그 외(2점 이상): 7일 정지
            -- 오늘을 기준으로 7일 뒤 23시59분59초까지 계정 정지
            ELSE V_PENALTY_END_DATE := TRUNC(SYSDATE + 7) + (1 - 1/86400);
        END CASE;

        INSERT INTO PENALTY_STATUS (PENALTY_STATUS_ID, PENALTY_ID, PENALTY_START_DATE, PENALTY_END_DATE)
        VALUES (PENALTY_STATUS_SEQ.NEXTVAL, N_PENALTY_ID, SYSDATE, V_PENALTY_END_DATE);
    END IF;



    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 납부';

    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID1
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '보증금 몰수';

