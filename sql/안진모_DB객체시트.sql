    -- 구매자 환급
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,USER_ID,N_MONEY_TYPE1,AUCTION_ID,AMOUNT
    FROM MONEY_TRANSACTION_HISTORY
    WHERE AUCTION_ID = N_AUCTION_ID
    AND MONEY_TYPE_ID = N_MONEY_TYPE3;

    -- 판매자 아이디
    SELECT USER_ID INTO N_USER_ID2
    FROM AUCTION_REGISTRATION A JOIN PRODUCT B
    ON A.PRODUCT_ID = B.PRODUCT_ID
