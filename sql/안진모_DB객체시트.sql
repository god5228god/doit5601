        RAISE_APPLICATION_ERROR(-20102,'입금되지않은 낙찰입니다.');

        WHEN NEW_ERR1
        THEN ROLLBACK;
        RAISE_APPLICATION_ERROR(-20101,'결제자와 입찰자가 다릅니다.');
        -- (구매확정)결제자 와 (낙찰)입찰자
        
        WHEN NEW_ERR2
        THEN ROLLBACK;
        RAISE_APPLICATION_ERROR(-20103,'발송되지않은 낙찰입니다.');

        WHEN OTHERS
        THEN ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('예외 발생 :'|| SQLERRM);
        RAISE_APPLICATION_ERROR(-20099,'실패');
