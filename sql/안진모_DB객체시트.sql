    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 환급';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE2
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 환급';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE3
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 납부';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE4
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 납부';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE5
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '결제';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE6
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '결제 대금';
    
    SELECT B.AUCTION_ID INTO N_AUCTION_ID
    FROM AUCTION_WINNING_RESULT A LEFT JOIN AUCTION_BID_PARTICIPATION B
    ON A.BID_ID = B.BID_ID
    WHERE A.BID_RESULT_ID = V_RESULT_ID;
    
    IF(N_MONEY_TYPE3 = 0)
        THEN RAISE_APPLICATION_ERROR(-20107,'머니 분류 테이블에 "구매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE1 = 0)
        THEN RAISE_APPLICATION_ERROR(-20108,'머니 분류 테이블에 "구매 보증금 환급" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE4 = 0)
        THEN RAISE_APPLICATION_ERROR(-20109,'머니 분류 테이블에 "판매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;

