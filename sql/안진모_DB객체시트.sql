    N_MONEY_TYPE_ID1 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID2 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID3 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID4 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_AUCTION_ID AUCTION_REGISTRATION.AUCTION_ID%TYPE;
    
    V_TOTAL_PENALTY_SCORE       PENALTY_HISTORY.PENALTY_SCORE%TYPE;
    V_PENALTY_END_DATE          PENALTY_STATUS.PENALTY_END_DATE%TYPE;
    N_PENALTY_ID                PENALTY_HISTORY.PENALTY_ID%TYPE;
