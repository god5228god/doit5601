-- ○ 9. 미결제 낙찰 대상 조회 뷰
CREATE OR REPLACE VIEW VW_UNPAID_WINNING_TARGET
AS
SELECT 
     A.AUCTION_ID          AS "경매번호"
    ,A.AUCTION_TITLE       AS "경매제목"
    ,U.USER_ID             AS "낙찰자번호"
    ,UA.USER_LOGIN_ID      AS "낙찰자ID"
    ,B.BID_PRICE           AS "낙찰금액"
    ,W.CREATED_AT          AS "낙찰일시"
    ,W.BID_RESULT_ID       AS "낙찰결과번호"
FROM AUCTION_WINNING_RESULT W
JOIN AUCTION_BID_PARTICIPATION B ON W.BID_ID = B.BID_ID
JOIN AUCTION_REGISTRATION A     ON B.AUCTION_ID = A.AUCTION_ID
JOIN USERS U                    ON B.USER_ID = U.USER_ID
JOIN USER_ACCOUNT UA            ON U.USER_ID = UA.USER_ID
WHERE NOT EXISTS (
    -- 이미 결제가 완료된 건 제외
    SELECT 1 
    FROM AUCTION_WINNING_PAYMENT P 
    WHERE P.BID_RESULT_ID = W.BID_RESULT_ID
)
AND NOT EXISTS (
    -- 이미 낙찰 실패 처리가 된 건 제외
    SELECT 1 
    FROM BID_FAILURE_HISTORY F 
    WHERE F.BID_RESULT_ID = W.BID_RESULT_ID
);


-- ○ 10. 경매 마감 임박 순서 뷰
CREATE OR REPLACE VIEW VW_AUCTION_URGENT_LIST
AS
SELECT VA.AUCTION_ID, VA.AUCTION_TITLE, VA.IMAGE_PATH_1, VA.BID_CURRENT_PRICE, UA.USER_LOGIN_ID, VA.AUCTION_END_DATE
   , ROW_NUMBER() OVER(ORDER BY VA.AUCTION_END_DATE DESC) AS RK
FROM VW_AUCTION_LIST VA 
    JOIN PRODUCT P ON VA.PRODUCT_ID = P.PRODUCT_ID
    JOIN USER_ACCOUNT UA ON P.USER_ID = UA.USER_ID
WHERE TO_DATE(AUCTION_END_DATE,'YYYY-MM-DD HH24:MI:SS') > SYSDATE;


-- ○ 11. 머니 거래 내역 조회 뷰
CREATE OR REPLACE VIEW VW_MONEY_HISTORY
AS
SELECT 
    USER_ID,
    '충전' AS TRANSACTION_TYPE, 
    CHARGE_AMOUNT AS AMOUNT,     
    TO_CHAR(CHARGED_AT, 'YYYY-MM-DD HH24:MI:SS') AS TRANSACTION_DATE,
    MCM.MONEY_CHARGE_METHOD_NAME AS DESCRIPTION 
FROM MONEY_CHARGE_HISTORY MCH
JOIN MONEY_CHARGE_METHOD MCM ON MCH.MONEY_CHARGE_METHOD_ID = MCM.MONEY_CHARGE_METHOD_ID
UNION ALL
SELECT 
    USER_ID,
    MT.MONEY_TYPE_NAME AS TRANSACTION_TYPE, 
    AMOUNT,                 
    TO_CHAR(CREATED_AT, 'YYYY-MM-DD HH24:MI:SS') AS TRANSACTION_DATE,
    MT.MONEY_TYPE_NAME AS DESCRIPTION     
FROM MONEY_TRANSACTION_HISTORY MTH
JOIN MONEY_TYPE MT ON MTH.MONEY_TYPE_ID = MT.MONEY_TYPE_ID;


-- ○ 12. 관리자 유저 조회 뷰
CREATE OR REPLACE VIEW VIEW_ADMIN_USER_LIST
AS
SELECT 
    U.USER_ID AS USERKEY           
    , A.USER_LOGIN_ID AS USERID    
    , P.USER_NAME AS USERNAME      
    , P.USER_PHONE AS USERTEL      
    -- 가입일이 없으면 오늘 날짜라도 나오게 처리
    , NVL((SELECT TO_CHAR(MIN(H.CREATED_AT), 'YYYY-MM-DD') 
           FROM ACCOUNT_EVENT_HISTORY H 
           WHERE H.USER_ID = U.USER_ID), TO_CHAR(SYSDATE, 'YYYY-MM-DD')) AS USERCREATED
    , CASE 
        WHEN S.PENALTY_STATUS_ID IS NOT NULL THEN '제재중'
        ELSE '정상'
      END AS USERSTATUS            
FROM USERS U
LEFT JOIN USER_ACCOUNT A ON U.USER_ID = A.USER_ID  
LEFT JOIN USER_PROFILE P ON U.USER_ID = P.USER_ID  
LEFT JOIN (
    SELECT PH.USER_ID, PS.PENALTY_STATUS_ID
    FROM PENALTY_HISTORY PH
    JOIN PENALTY_STATUS PS ON PH.PENALTY_ID = PS.PENALTY_ID
    WHERE CURRENT_DATE BETWEEN PS.PENALTY_START_DATE AND PS.PENALTY_END_DATE
) S ON U.USER_ID = S.USER_ID;

-- ○ 13. 관리자 유저 상세조회 뷰
CREATE OR REPLACE VIEW VIEW_USER_INFO
AS
SELECT 
    U.USER_ID
    , UA.USER_LOGIN_ID
    , UA.USER_PASSWORD
    , UP.USER_NAME
    , UP.USER_SSN
    , UP.USER_EMAIL
    , UP.USER_PHONE
    , UP.USER_ZIPCODE
    , UP.USER_ADDRESS
    , UP.USER_ADDRESS_DETAIL
    , FN_GET_USER_MONEY_BALANCE(U.USER_ID) AS TOTAL_MONEY
    -- 1. 가입일시 추가 (이력 테이블에서 최초 발생일 가져오기, 없을 시 현재날짜)
    , NVL((SELECT TO_CHAR(MIN(H.CREATED_AT), 'YYYY-MM-DD HH24:MI:SS') 
           FROM ACCOUNT_EVENT_HISTORY H 
           WHERE H.USER_ID = U.USER_ID), TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS')) AS CREATED_AT
    -- 2. 계정 상태 추가 (패널티 이력 확인)
    , CASE 
        WHEN S.PENALTY_STATUS_ID IS NOT NULL THEN '제재중'
        ELSE '정상'
      END AS USER_STATUS
FROM USERS U 
LEFT JOIN USER_ACCOUNT UA ON U.USER_ID = UA.USER_ID
LEFT JOIN USER_PROFILE UP ON U.USER_ID = UP.USER_ID
LEFT JOIN (
    -- 현재 활성화된 패널티가 있는지 확인하기 위한 조인용 서브쿼리
    SELECT PH.USER_ID, PS.PENALTY_STATUS_ID
    FROM PENALTY_HISTORY PH
    JOIN PENALTY_STATUS PS ON PH.PENALTY_ID = PS.PENALTY_ID
    WHERE CURRENT_DATE BETWEEN PS.PENALTY_START_DATE AND PS.PENALTY_END_DATE
) S ON U.USER_ID = S.USER_ID;



