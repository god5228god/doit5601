-- 구매 확정 자동 처리 스케줄러용 프로시저
-- 구매 확정 자동 처리 스케줄러(프로시저)(컴파일O,테스트X)
CREATE OR REPLACE PROCEDURE PRC_AUTO_PURCHASE_CONFIRM
IS
    N_MONEY_TYPE_ID1 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID2 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID3 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID4 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID5 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID6 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
BEGIN

    -- 구매 확정 이력
    INSERT INTO PURCHASE_CONFIRM_HISTORY(PURCHASE_CONFIRM_ID,SHIPPING_ID)
    SELECT PURCHASE_CONFIRM_SEQ.NEXTVAL,M.SHIPPING_ID
    FROM
        (
            SELECT A.SHIPPING_ID
            FROM DELIVERY_COMPLETED A LEFT JOIN PURCHASE_CONFIRM_HISTORY B
            ON A.SHIPPING_ID = B.SHIPPING_ID
            WHERE B.SHIPPING_ID IS NULL
            AND A.CREATED_AT+3 < SYSDATE
        )M;

    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID1
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 환급';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID2
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 납부';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID3
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 환급';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID4
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 납부';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID5
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '결제';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID6
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '결제 대금';
    
    IF(N_MONEY_TYPE_ID2 = 0)
        THEN RAISE_APPLICATION_ERROR(-20107,'머니 분류 테이블에 "구매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID1 = 0)
        THEN RAISE_APPLICATION_ERROR(-20108,'머니 분류 테이블에 "구매 보증금 환급" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID4 = 0)
        THEN RAISE_APPLICATION_ERROR(-20109,'머니 분류 테이블에 "판매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID3 = 0)
        THEN RAISE_APPLICATION_ERROR(-20110,'머니 분류 테이블에 "판매 보증금 환급" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID5 = 0)
        THEN RAISE_APPLICATION_ERROR(-20112,'머니 분류 테이블에 "결제" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID6 = 0)
        THEN RAISE_APPLICATION_ERROR(-20113,'머니 분류 테이블에 "결제 대금" 코드명이 존재하지 않습니다');
    END IF;

    -- 구매 보증금 환급
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,F.USER_ID,N_MONEY_TYPE_ID1,F.AUCTION_ID,G.AMOUNT
    FROM PURCHASE_CONFIRM_HISTORY A 
    INNER JOIN DELIVERY_COMPLETED C
    ON A.SHIPPING_ID = C.SHIPPING_ID
    INNER JOIN AUCTION_WINNING_PAYMENT D
    ON C.PAYMENT_ID = D.PAYMENT_ID
    INNER JOIN AUCTION_WINNING_RESULT E
    ON D.BID_RESULT_ID = E.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION F
    ON E.BID_ID = F.BID_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY G
    ON F.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID2
    LEFT JOIN MONEY_TRANSACTION_HISTORY H
    ON H.USER_ID = G.USER_ID AND H.AUCTION_ID = G.AUCTION_ID
    AND H.MONEY_TYPE_ID = N_MONEY_TYPE_ID1
    WHERE H.MONEY_ID IS NULL;
    -- GROUP BY F.USER_ID
    
    -- 판매보증금 환급
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,J.USER_ID,N_MONEY_TYPE_ID3,F.AUCTION_ID,G.AMOUNT
    FROM PURCHASE_CONFIRM_HISTORY A 
    INNER JOIN DELIVERY_COMPLETED C
    ON A.SHIPPING_ID = C.SHIPPING_ID
    INNER JOIN AUCTION_WINNING_PAYMENT D
    ON C.PAYMENT_ID = D.PAYMENT_ID
    INNER JOIN AUCTION_WINNING_RESULT E
    ON D.BID_RESULT_ID = E.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION F
    ON E.BID_ID = F.BID_ID
    INNER JOIN AUCTION_REGISTRATION I
    ON F.AUCTION_ID = I.AUCTION_ID
    INNER JOIN PRODUCT J
    ON I.PRODUCT_ID = J.PRODUCT_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY G
    ON J.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID4
    LEFT JOIN MONEY_TRANSACTION_HISTORY H
    ON H.USER_ID = G.USER_ID AND H.AUCTION_ID = G.AUCTION_ID
    AND H.MONEY_TYPE_ID = N_MONEY_TYPE_ID3
    WHERE H.MONEY_ID IS NULL;
    
    -- 구매대금 판매자에게 이력추가
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,J.USER_ID,N_MONEY_TYPE_ID6,F.AUCTION_ID,G.AMOUNT
    FROM PURCHASE_CONFIRM_HISTORY A 
    INNER JOIN DELIVERY_COMPLETED C
    ON A.SHIPPING_ID = C.SHIPPING_ID
    INNER JOIN AUCTION_WINNING_PAYMENT D
    ON C.PAYMENT_ID = D.PAYMENT_ID
    INNER JOIN AUCTION_WINNING_RESULT E
    ON D.BID_RESULT_ID = E.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION F
    ON E.BID_ID = F.BID_ID
    INNER JOIN AUCTION_REGISTRATION I
    ON F.AUCTION_ID = I.AUCTION_ID
    INNER JOIN PRODUCT J
    ON I.PRODUCT_ID = J.PRODUCT_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY G
    ON F.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID5
    LEFT JOIN MONEY_TRANSACTION_HISTORY H
    ON H.USER_ID = G.USER_ID AND H.AUCTION_ID = G.AUCTION_ID
    AND H.MONEY_TYPE_ID = N_MONEY_TYPE_ID6
    WHERE H.MONEY_ID IS NULL;
    
    -- 구매 확정 이력
    INSERT INTO TRANSACTION_COMPLETED(TRANSACTION_ID,PURCHASE_CONFIRM_ID)
    SELECT TRANSACTION_SEQ.NEXTVAL,A.PURCHASE_CONFIRM_ID
    FROM PURCHASE_CONFIRM_HISTORY A LEFT JOIN TRANSACTION_COMPLETED B
    ON A.PURCHASE_CONFIRM_ID = B.PURCHASE_CONFIRM_ID
    WHERE B.TRANSACTION_ID IS NULL;

    COMMIT;

    EXCEPTION
    WHEN OTHERS
        THEN ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('예외 발생 :'|| SQLERRM);
        RAISE_APPLICATION_ERROR(-20099,'실패');
END;
