    INSERT INTO PENALTY_HISTORY(PENALTY_ID,USER_ID,PENALTY_TYPE_ID,ADMIN_ACCOUNT_ID,PENALTY_SCORE)
    VALUES(N_PENALTY_ID,V_USER_ID,N_PENALTY_TYPE_ID,NULL,1);
    
