--  낙찰 결제 기한 확인 스케줄러용 프로시저
-- 낙찰 결제 기한 확인 스케줄러(프로시저) -- 실행 불가
CREATE OR REPLACE PROCEDURE REC_AUCTION_CLOSE
IS
    N_BID_FAIL_TYPE_ID BID_FAILURE_TYPE.BID_FAIL_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID1 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID2 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID3 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_MONEY_TYPE_ID4 MONEY_TYPE.MONEY_TYPE_ID%TYPE;
    N_PENALTY_TYPE_ID PENALTY_ASSIGN_TYPE.PENALTY_TYPE_ID%TYPE;
BEGIN

    SELECT NVL(BID_FAIL_TYPE_ID,0) INTO N_BID_FAIL_TYPE_ID
    FROM BID_FAILURE_TYPE
    WHERE BID_FAIL_TYPE_NAME = '결제기한만료';
    
    IF(N_BID_FAIL_TYPE_ID = 0)
        THEN RAISE_APPLICATION_ERROR(-20105,'낙찰실패타입 테이블에 "결제기한만료" 코드명이 존재하지 않습니다');
    END IF;

    -- 낙찰 실패 이력
    INSERT INTO (BID_FAIL_HISTORY_ID,BID_RESULT_ID,BID_FAIL_TYPE_ID)
    SELECT BID_FAIL_HISTORY_SEQ.NEXTVAL,M.BID_RESULT_ID,N_BID_FAIL_TYPE_ID
    FROM
        (
            SELECT A.BID_RESULT_ID
            ,CASE 
             WHEN A.CREATED_AT IS NULL THEN '오류'
             WHEN A.CREATED_AT+1 >= SYSDATE THEN '안전'
             WHEN A.CREATED_AT+1 < SYSDATE THEN '마감'
             ELSE '오류'
             END AS CREATED_AT
            FROM AUCTION_WINNING_RESULT A LEFT JOIN AUCTION_WINNING_PAYMENT B
            ON A.BID_RESULT_ID = B.BID_RESULT_ID
            LEFT JOIN BID_FAILURE_HISTORY C
            ON A.BID_RESULT_ID = C.BID_RESULT_ID
            WHERE B.BID_RESULT_ID IS NULL AND C.BID_RESULT_ID IS NULL
        )M
    WHERE M.CREATED_AT = '마감';


    SELECT NVL(PENALTY_TYPE_ID,0) INTO N_PENALTY_TYPE_ID
    FROM PENALTY_ASSIGN_TYPE
    WHERE PENALTY_TYPE_NAME = '자동';

    IF(N_PENALTY_TYPE_ID = 0)
        THEN RAISE_APPLICATION_ERROR(-20111,'패널티 분류 코드명에 "자동"인 코드명이 존재하지 않습니다');
    END IF;


    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '보증금 몰수';

    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID1
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 납부';

    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID2
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '구매 보증금 환급';

    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID3
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 납부';
    
    SELECT NVL(MONEY_TYPE_ID,0) INTO N_MONEY_TYPE_ID4
    FROM MONEY_TYPE
    WHERE MONEY_TYPE_NAME = '판매 보증금 환급';
    
    
    IF(N_MONEY_TYPE_ID = 0)
        THEN RAISE_APPLICATION_ERROR(-20106,'머니 분류 테이블에 "보증금 몰수" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID1 = 0)
        THEN RAISE_APPLICATION_ERROR(-20107,'머니 분류 테이블에 "구매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID2 = 0)
        THEN RAISE_APPLICATION_ERROR(-20108,'머니 분류 테이블에 "구매 보증금 환급" 코드명이 존재하지 않습니다');
    END IF;

    IF(N_MONEY_TYPE_ID3 = 0)
        THEN RAISE_APPLICATION_ERROR(-20109,'머니 분류 테이블에 "판매 보증금 납부" 코드명이 존재하지 않습니다');
    END IF;
    
    IF(N_MONEY_TYPE_ID4 = 0)
        THEN RAISE_APPLICATION_ERROR(-20110,'머니 분류 테이블에 "판매 보증금 환급" 코드명이 존재하지 않습니다');
    END IF;
    

    -- 패널티 입력(대기)
    INSERT INTO PENALTY_HISTORY(PENALTY_ID,USER_ID,PENALTY_TYPE_ID,ADMIN_ACCOUNT_ID,PENALTY_SCORE)
    SELECT PENALTY_SEQ.NEXTVAL,C.USER_ID,N_PENALTY_TYPE_ID,NULL,1
     FROM BID_FAILURE_HISTORY A INNER JOIN AUCTION_WINNING_RESULT B
     ON A.BID_RESULT_ID = B.BID_RESULT_ID
     INNER JOIN AUCTION_BID_PARTICIPATION C
     ON B.BID_ID = C.BID_ID
     LEFT JOIN MONEY_TRANSACTION_HISTORY D
     ON C.AUCTION_ID = D.AUCTION_ID AND C.USER_ID = D.USER_ID
     AND D.MONEY_TYPE_ID = N_MONEY_TYPE_ID
     WHERE D.MONEY_ID IS NULL;

    -- 구매자 보증금 환급 이력(수정 : 환급 -> 몰수)
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
     SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,C.USER_ID,N_MONEY_TYPE_ID,C.AUCTION_ID,0
     FROM BID_FAILURE_HISTORY A INNER JOIN AUCTION_WINNING_RESULT B
     ON A.BID_RESULT_ID = B.BID_RESULT_ID
     INNER JOIN AUCTION_BID_PARTICIPATION C
     ON B.BID_ID = C.BID_ID
     INNER JOIN MONEY_TRANSACTION_HISTORY D
     ON C.AUCTION_ID = D.AUCTION_ID AND C.USER_ID = D.USER_ID
     AND D.MONEY_TYPE_ID = N_MONEY_TYPE_ID1
     LEFT JOIN MONEY_TRANSACTION_HISTORY E
     ON C.AUCTION_ID = E.AUCTION_ID AND C.USER_ID = E.USER_ID
     AND E.MONEY_TYPE_ID = N_MONEY_TYPE_ID
     WHERE E.MONEY_ID IS NULL;

     -- 실구매자 이외 구매자 환급 이력(대기)
    -- INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    -- ,AUCTION_ID,AMOUNT)
    -- SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,A.USER_ID,N_MONEY_TYPE_ID2,A.AUCTION_ID,D.AMOUNT
    --  FROM AUCTION_BID_PARTICIPATION A LEFT JOIN AUCTION_WINNING_RESULT B
    --  ON A.BID_ID = B.BID_ID
    --  LEFT JOIN BID_FAILURE_HISTORY C
    --  ON B.BID_RESULT_ID = C.BID_RESULT_ID
    --  LEFT JOIN MONEY_TRANSACTION_HISTORY D
    --  ON A.USER_ID = D.USER_ID AND A.AUCTION_ID = D.AUCTION_ID
    --  AND D.MONEY_TYPE_ID = N_MONEY_TYPE_ID1
    --  LEFT JOIN MONEY_TRANSACTION_HISTORY E
    --  ON A.USER_ID = E.USER_ID AND A.AUCTION_ID = E.AUCTION_ID
    --  AND E.MONEY_TYPE_ID = N_MONEY_TYPE_ID2
    --  WHERE B.BID_ID IS NULL
    --  AND E.MONEY_TYPE_ID IS NULL
    --  AND C;

     -- 실구매자 이외 구매자 환급 이력
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID, USER_ID, MONEY_TYPE_ID, AUCTION_ID, AMOUNT)
    SELECT 
    MONEY_TRANSACTION_SEQ.NEXTVAL
    ,A.USER_ID
    ,N_MONEY_TYPE_ID2       -- 구매 보증금 환급
    ,A.AUCTION_ID
    ,D.AMOUNT
    FROM AUCTION_BID_PARTICIPATION A
-- 보증금 납부 이력 (환급 금액 가져오기)
    INNER JOIN MONEY_TRANSACTION_HISTORY D
    ON A.USER_ID = D.USER_ID 
    AND A.AUCTION_ID = D.AUCTION_ID
    AND D.MONEY_TYPE_ID = N_MONEY_TYPE_ID1  -- 구매 보증금 납부
-- 아직 환급 안 된 사람만
    LEFT JOIN MONEY_TRANSACTION_HISTORY E
    ON A.USER_ID = E.USER_ID 
    AND A.AUCTION_ID = E.AUCTION_ID
    AND E.MONEY_TYPE_ID = N_MONEY_TYPE_ID2  -- 구매 보증금 환급
-- 낙찰 실패가 발생한 경매인지 확인
    WHERE A.AUCTION_ID IN (
    SELECT BP.AUCTION_ID
    FROM AUCTION_BID_PARTICIPATION BP
    INNER JOIN AUCTION_WINNING_RESULT WR ON BP.BID_ID = WR.BID_ID
    INNER JOIN BID_FAILURE_HISTORY FH ON WR.BID_RESULT_ID = FH.BID_RESULT_ID
    )
    -- 실구매자(낙찰자) 제외
    AND A.BID_ID NOT IN (
    SELECT WR2.BID_ID
    FROM AUCTION_WINNING_RESULT WR2
    INNER JOIN BID_FAILURE_HISTORY FH2 ON WR2.BID_RESULT_ID = FH2.BID_RESULT_ID
    )
    AND E.MONEY_ID IS NULL;
    
    
    -- 판매자 보증금 몰수(수정: 몰수 -> 환급)
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,E.USER_ID,N_MONEY_TYPE_ID4,C.AUCTION_ID,F.AMOUNT
    FROM BID_FAILURE_HISTORY A INNER JOIN AUCTION_WINNING_RESULT B
    ON A.BID_RESULT_ID = B.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION C
    ON B.BID_ID = C.BID_ID
    INNER JOIN AUCTION_REGISTRATION D
    ON C.AUCTION_ID = D.AUCTION_ID
    INNER JOIN PRODUCT E
    ON D.PRODUCT_ID = E.PRODUCT_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY F
    ON E.USER_ID = F.USER_ID AND F.AUCTION_ID = D.AUCTION_ID
    AND F.MONEY_TYPE_ID = N_MONEY_TYPE_ID3
    LEFT JOIN MONEY_TRANSACTION_HISTORY G
    ON E.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID4
    WHERE G.MONEY_ID IS NULL;
    
    COMMIT;
    
    EXCEPTION
        WHEN OTHERS
        THEN ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('예외 발생 :'|| SQLERRM);
        RAISE_APPLICATION_ERROR(-20099,'실패');
    
END;


